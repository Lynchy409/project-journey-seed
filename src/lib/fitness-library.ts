function movement(
  name: string,
  category: string,
  kind: string,
  purpose: FitnessSlot,
  equipment: string,
  cue: string,
  reference: string,
  referenceName: string,
  caution = "",
): Movement {
  return {
    id: name.toLowerCase().replaceAll(/[^a-z0-9]+/g, "-"),
    name,
    category,
    kind,
    purpose,
    equipment,
    cue,
    reference,
    referenceName,
    caution,
  };
}
